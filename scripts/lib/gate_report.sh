#!/usr/bin/env bash
# =============================================================
# 门槛执行与「失败报告」的唯一实现（`scripts/preflight.sh` 与冒烟脚本共用）
#
# 【为什么抽成单独文件】
# 「门槛红的时候能不能拿到失败项的名字」这件事，2026-09-20 之前**只是一条写
# 在「仍开着」表里的建议**（「下次输出要落盘再 grep」），没有任何机制保证它发生
# ⇒ 那次门槛红了却不知道红的是谁，至今追不回来。
#
# 抽出来的唯一目的是让它**有行为测试**：`scripts/test/gate_report_smoke.sh`
# 直接 source 本文件、喂一个必失败的假门槛，几毫秒内验证「名字被摘出来 +
# 日志被留住」。若 `run_gate` 留在 preflight.sh 里，就只能做源码文本断言 ——
# 那种断言守得住「那行还在」，守不住「改坏了但还在」。
#
# 【调用方必须先设置】
#   LOG        —— 门槛输出写到哪里（run_gate 每次覆盖它）
#   KEEP_DIR   —— 失败时全量日志另存到哪里（必须已存在）
#   FAIL_TAIL  —— 失败回显行数（0 = 全量）
#   读取：GATE_NO（本文件维护）、FAILED（调用方累加）
# =============================================================

# 统一的门槛标题（含递增编号），保证「前置条件失败」与「命令失败」两种路径编号一致。
gate_header() {
    GATE_NO=$((GATE_NO + 1))
    echo ""
    echo "▶ 门槛 ${GATE_NO}：$1"
}

# 失败回显行数：默认 30（本地迭代够用），**`0` = 全量回显**（CI 用）。
# （冒烟脚本设 `PREFLIGHT_FAIL_TAIL=2` 来构造「名字正好被 tail 截掉」那一档 ——
#   走的是**真实**环境变量这条路，不额外发明一个开关。）
#
# ⚠️ **这一行必须与下面 `if [ "$FAIL_TAIL" = "0" ]` 那个分支在**同一个文件**里** ——
#    `GateParityTests/脚本必须认契约里那个值` 守的就是这件事：**读了**环境变量与
#    **按它的值分支**要在同一处。分在两处的话：改了读的那侧（或像 2026-09-20 那样
#    把分支搬去别的文件），两边各自都成立、谁都不报错，而 `0` 会落进别的语义
#    （`tail -n 0` 把日志**整个抹掉**，比不设还糟）。
FAIL_TAIL="${PREFLIGHT_FAIL_TAIL:-30}"

# run_gate <标题> <命令...>
# 输出重定向到日志：成功只回显尾部 3 行（保留覆盖率数字这类关键摘要），
# 失败回显尾部若干行供定位。**不把命令输出直接接到管道上**——`cmd | tail` 会让
# `$?` 变成 tail 的状态，把失败判成成功（本项目踩过这个坑）。
#
# 失败回显行数由 `PREFLIGHT_FAIL_TAIL` 控制：默认 30（本地迭代够用），
# **`0` = 全量回显**（CI 用）。
#
# 为什么必须有「全量」这一档：2026-09-17 CI 门槛 3 红了 **19 个 issue**，
# 而 `tail -30` 只露出 12 个 —— 被截掉的正好是**断言消息**所在的位置
# （swift-testing 的 issue 详情混在通过行之间），于是本地只能靠猜。
# 截断日志把「一次能查清的事」变成「要反复推 CI 猜」，这才是真正的浪费。
run_gate() {
    local title="$1"
    shift
    gate_header "$title"
    if "$@" > "$LOG" 2>&1; then
        sed 's/^/     /' "$LOG" | tail -3
        echo "   ✓ 通过"
        return 0
    fi
    # ⚠️ **先把「失败项的名字」摘出来，再回显日志**。
    # 名字混在几百行通过日志之间，被 `tail` 截掉的概率很高；而「不知道哪条红了」
    # 与「红得莫名其妙」一样贵 —— 2026-09-20 那次就是这么丢的。
    local keep="${KEEP_DIR}/门槛${GATE_NO}.log"
    cp "$LOG" "$keep"
    echo "   ✗ 未通过。**全量日志已保留**：${keep}"
    local summary
    summary="$(grep -nE '✘|✗|❌|error:|failed|未通过|issue' "$LOG" | head -20 || true)"
    if [ -n "$summary" ]; then
        echo "   ── 失败项摘要（先看这里，别直接从日志尾部猜）──"
        printf '%s\n' "$summary" | sed 's/^/     /'
    fi
    if [ "$FAIL_TAIL" = "0" ]; then
        echo "   ── 日志全量回显（PREFLIGHT_FAIL_TAIL=0）──"
        sed 's/^/     /' "$LOG"
    else
        echo "   ── 日志尾部 ${FAIL_TAIL} 行（设 PREFLIGHT_FAIL_TAIL=0 可全量回显）──"
        sed 's/^/     /' "$LOG" | tail -n "$FAIL_TAIL"
    fi
    return 1
}
